const table = document.getElementById("result");

function resetFeatureBtns() {
	for (let i = 0; i < features.length;i++) {
		const btn = document.getElementById("fb" + i);
		btn.value = features[i][0];
		btn.className = "zero";
	}
}

resetFeatureBtns();

function fb(i) {
	const btn = document.getElementById("fb" + i);
	if (btn.className === "zero") {
		btn.value = features[i][1];
		btn.className = "one";
	}
	else if (btn.className === "one") {
		btn.value = features[i][0];
		btn.className = "zero";
	}

	calculate(false);
	
}

function toBase4(val) {
	let result = [];

	while (val > 0) {
		result.push(val % 4);
		val = Math.floor(val / 4);
	}
	return result;
}

let lastEnteredYokai = true;
let selectedGame = 0;

function gameChange() {
	const game = document.getElementById("game").value;
	document.getElementById("yk").setAttribute("list", "yks" + game);
	selectedGame = game;

	calculate(lastEnteredYokai);
}

function calculate(enteredYokai) {
	lastEnteredYokai = enteredYokai;
	clearResult();

	if (enteredYokai) {
		const yokai = document.getElementById("yk").value;
		if (!(yokai in yks[selectedGame])) return;

		document.getElementById("resTxt").innerHTML = "This Yo-kai is created by one of these faces:";
		
		const titleRow = document.createElement("tr");
		const dataRow = document.createElement("tr");

		let i = 1;
		for (let id of yks[selectedGame][yokai]) {
			const title = document.createElement("th");
			title.innerHTML = "Face " + i;
			titleRow.append(title);

			dataRow.append(createFeatureCol(toBase4(id)))

			i++;
		}


		table.append(titleRow);
		table.append(dataRow);
	}else {
		createFeatureResult();
	}
}

function createFeatureCol(feats) {
	const col = document.createElement("td");

	let i = 0;
	for (let i in features) {
		const feat = feats.length > i ? feats[i] : 0;

		const featBtn = document.createElement("input");
		featBtn.type = "button";
		featBtn.disabled = true;
		featBtn.value = features[i][feat];

		if (feat == 0) featBtn.className = "zero";
		if (feat == 1) featBtn.className = "one";

		col.append(featBtn);
		col.append(document.createElement("br"));
		i++;
	}

	return col;
}

function createFeatureResult() {
	let id = 0;
	for (let i in features) {
		id *= 4;

		if (document.getElementById("fb" + i).className == "one") id += 1;
	}

	let yk = "";
	for (let yokai in yks[selectedGame]) {
		if (yks[selectedGame][yokai].includes(id)) {
			yk = yokai;
			break;
		}
	}

	document.getElementById("resTxt").innerHTML = "This face would be inspirited by " + yk;

}

function clearResult() {
	table.innerHTML = "";
	document.getElementById("resTxt").innerHTML = "";

	if (lastEnteredYokai) {
		resetFeatureBtns();
	}else {
		document.getElementById("yk").value = "";
	}
}
